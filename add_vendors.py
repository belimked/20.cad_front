import json
import os
import sys
from typing import List, Dict, Any


def load_existing_vendors(file_path: str) -> List[Dict]:
    """
    读取现有的供应商 JSON 文件
    
    Args:
        file_path: JSON 文件路径
        
    Returns:
        供应商数据列表
    """
    try:
        if not os.path.exists(file_path):
            print(f"文件不存在: {file_path}")
            return []
            
        with open(file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
            
        if not isinstance(data, list):
            print(f"错误：JSON 文件格式不正确，期望数组格式")
            return []
            
        return data
    except json.JSONDecodeError as e:
        print(f"JSON 解析错误: {e}")
        return []
    except Exception as e:
        print(f"读取文件失败: {e}")
        return []


def get_next_vendor_id(vendors: List[Dict]) -> int:
    """
    获取下一个可用的 vendorid
    
    Args:
        vendors: 现有供应商数据列表
        
    Returns:
        下一个可用的 vendorid
    """
    if not vendors:
        return 1
        
    max_id = 0
    for vendor in vendors:
        if 'vendorid' in vendor and isinstance(vendor['vendorid'], int):
            max_id = max(max_id, vendor['vendorid'])
            
    return max_id + 1


def clean_vendor_name(name: str) -> str:
    """
    清理供应商名称
    
    Args:
        name: 原始供应商名称
        
    Returns:
        清理后的供应商名称
    """
    if not name:
        return ""
        
    # 去除首尾空格
    cleaned = name.strip()
    
    # 去除多余的空格
    cleaned = ' '.join(cleaned.split())
    
    return cleaned


def parse_vendor_data(data_text: str) -> List[str]:
    """
    解析制表符分隔的供应商数据
    
    Args:
        data_text: 制表符分隔的数据文本
        
    Returns:
        供应商名称列表
    """
    vendor_names = []
    lines = data_text.strip().split('\n')
    
    for line_num, line in enumerate(lines, 1):
        line = line.strip()
        if not line:
            continue
            
        # 按制表符分割
        parts = line.split('\t')
        if len(parts) >= 1:
            vendor_name = clean_vendor_name(parts[0])
            if vendor_name:
                vendor_names.append(vendor_name)
            else:
                print(f"警告：第 {line_num} 行的供应商名称为空，已跳过")
        else:
            print(f"警告：第 {line_num} 行格式不正确，已跳过")
            
    return vendor_names


def create_vendor_objects(vendor_names: List[str], start_id: int) -> List[Dict]:
    """
    创建新的供应商 JSON 对象
    
    Args:
        vendor_names: 供应商名称列表
        start_id: 起始 vendorid
        
    Returns:
        新的供应商对象列表
    """
    vendor_objects = []
    current_id = start_id
    
    for name in vendor_names:
        vendor_obj = {
            "vendorname": name,
            "vendorid": current_id
        }
        vendor_objects.append(vendor_obj)
        current_id += 1
        
    return vendor_objects


def check_duplicates(existing_vendors: List[Dict], new_vendors: List[Dict]) -> List[Dict]:
    """
    检查并去除重复的供应商
    
    Args:
        existing_vendors: 现有供应商列表
        new_vendors: 新供应商列表
        
    Returns:
        去重后的新供应商列表
    """
    existing_names = set()
    for vendor in existing_vendors:
        if 'vendorname' in vendor:
            existing_names.add(vendor['vendorname'])
    
    filtered_vendors = []
    duplicates = []
    
    for vendor in new_vendors:
        vendor_name = vendor['vendorname']
        if vendor_name in existing_names:
            duplicates.append(vendor_name)
        else:
            filtered_vendors.append(vendor)
            existing_names.add(vendor_name)
    
    if duplicates:
        print(f"发现 {len(duplicates)} 个重复的供应商，已跳过：")
        for name in duplicates[:5]:  # 只显示前5个
            print(f"  - {name}")
        if len(duplicates) > 5:
            print(f"  ... 还有 {len(duplicates) - 5} 个")
    
    return filtered_vendors


def save_vendors_file(file_path: str, vendors: List[Dict]) -> bool:
    """
    保存供应商数据到 JSON 文件
    
    Args:
        file_path: JSON 文件路径
        vendors: 供应商数据列表
        
    Returns:
        是否保存成功
    """
    try:
        with open(file_path, 'w', encoding='utf-8') as f:
            json.dump(vendors, f, ensure_ascii=False, indent=2)
        return True
    except Exception as e:
        print(f"保存文件失败: {e}")
        return False


